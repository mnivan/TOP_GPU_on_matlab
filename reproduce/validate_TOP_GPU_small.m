function validate_TOP_GPU_small()
% Validate TOP_GPU's actual GPU operators on a small case1-like cuboid.
% Run only when the GPU is available. Produces one ValidationReport.txt per path.
% The 16x8x8 mesh preserves case1's 2:1:1 proportions and is small enough
% for explicit sparse assembly. The production case1 remains 96x48x48.
% For the manuscript's FD table, read Probe positive_direction at h=1e-4
% in each ValidationReport.txt (the earlier step sweep uses a different probe).
standardDomain = true(8,16,8);
superDomain = true(8,16,8);
TOP_GPU(standardDomain,'optCase',1,'consType','GLOBAL','V0',0.5,'nLoop',1, ...
    'rMin',sqrt(3),'ft',2,'filter_method','pde','numLevels',3, ...
    'super_element',0,'mixed_Precision',0,'tol',1e-10, ...
    'validationOnly',true);
TOP_GPU(superDomain,'optCase',1,'consType','GLOBAL','V0',0.5,'nLoop',1, ...
    'rMin',sqrt(3),'ft',2,'filter_method','distance','numLevels',3, ...
    'super_element',1,'Num_',4,'mixed_Precision',0,'tol',1e-10, ...
    'validationOnly',true);
end
